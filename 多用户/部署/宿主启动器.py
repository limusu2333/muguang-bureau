def _启动新角色(role: str, *, migration: bool) -> float:
    domain = f"gui/{os.getuid()}"
    status = RUNTIME / "status" / f"{role}.json"
    status.unlink(missing_ok=True)
    started_at = time.time()
    # A prior failed migration may have left the sealed single-process
    # fallback loaded.  Unload it before binding any of the three ports.
    # The plist remains on disk as the emergency recovery description.
    _launchctl("bootout", domain, str(FALLBACK_PLIST), check=False)
    plist = ROLE_PLISTS[role]
    if not plist.is_file() or plist.is_symlink():
        raise 宿主启动错误(f"{role} 的正式启动描述尚未准备")
    # 暂存候选时磁盘上的 plist 已替换为候选运行环境。无论这是首次迁移
    # 还是后续发布，都必须重新 bootstrap（让 macOS 重新读取启动文件）。
    # 只 kickstart 会继续使用 launchd 内存里的旧配置；任务尚未加载时还会
    # 直接返回 113。
    _launchctl("bootout", domain, str(plist), check=False)
    try:
        _launchctl("bootstrap", domain, str(plist))
    except subprocess.CalledProcessError as exc:
        detail = str(exc.stderr or exc.stdout or "").strip().replace("\n", " ")[:240]
        suffix = f"：{detail}" if detail else ""
        raise 宿主启动错误(f"{role} 的正式服务没有加载成功{suffix}") from exc
    return started_at


def _恢复冻结正式单进程(
    started_roles: list[str], *, version: str, source_sha256: str,
) -> str:
    domain = f"gui/{os.getuid()}"
    failures: list[str] = []
    # Stop every role description, not only roles recorded as started.  A
    # launchctl/bootstrap failure can happen after a process has bound its
    # port but before the helper records it; leaving that process alive would
    # make the fallback fail with an address-in-use error.
    for role in reversed(tuple(ROLE_PLISTS)):
        try:
            _launchctl("bootout", domain, str(ROLE_PLISTS[role]), check=False)
        except Exception as exc:
            failures.append(f"{role} 停止失败：{type(exc).__name__}")
    if not FALLBACK_PLIST.is_file() or FALLBACK_PLIST.is_symlink():
        failures.append("冻结正式单进程启动项不存在")
    else:
        try:
            active = 解析活动发布(ACTIVE_LOCK)
            roles = _正式角色列表(Path(str(active["source_path"])))
            for role in ROLE_SETTINGS:
                (RUNTIME / "status" / f"{role}.json").unlink(missing_ok=True)
            started_at = time.time()
            _launchctl("bootout", domain, str(FALLBACK_PLIST), check=False)
            _launchctl("bootstrap", domain, str(FALLBACK_PLIST))
            for role in roles:
                _等待角色(
                    role,
                    version=version,
                    source_sha256=source_sha256,
                    started_at=started_at,
                )
        except Exception as exc:
            detail = str(exc).strip() or type(exc).__name__
            failures.append(f"冻结正式单进程恢复失败：{detail[:240]}")
    return "已从激活的冻结正式副本恢复三端口" if not failures else "；".join(failures)


def 恢复活动冻结正式后台() -> dict[str, Any]:
    """从当前活动的封存版本恢复正式后台，并确认该版本拥有的入口全部在线。"""
    active = 解析活动发布(ACTIVE_LOCK)
    version = str(active["version"])
    source_sha256 = str(active["source_sha256"])
    roles = _正式角色列表(Path(str(active["source_path"])))
    result = _恢复冻结正式单进程(
        [], version=version, source_sha256=source_sha256,
    )
    if result != "已从激活的冻结正式副本恢复三端口":
        raise 宿主启动错误(result)
    return {
        "status": "restored",
        "mode": "formal-fallback",
        "version": version,
        "source_sha256": source_sha256,
        "roles": list(roles),
    }


def 恢复活动正式后台() -> dict[str, Any]:
    """从活动封存版恢复独立宿主；失败时只把备用进程作为应急保障。"""
    active = 解析活动发布(ACTIVE_LOCK)
    version = str(active["version"])
    source_sha256 = str(active["source_sha256"])
    available = set(_正式角色列表(Path(str(active["source_path"]))))
    roles = tuple(role for role in ("control", "rerank", "admin") if role in available)
    started_roles: list[str] = []
    try:
        for role in roles:
            started_at = _启动新角色(role, migration=False)
            started_roles.append(role)
            _等待角色(
                role,
                version=version,
                source_sha256=source_sha256,
                started_at=started_at,
            )
    except BaseException as exc:
        fallback = _恢复冻结正式单进程(
            started_roles,
            version=version,
            source_sha256=source_sha256,
        )
        detail = str(exc).strip() or type(exc).__name__
        raise 宿主启动错误(
            f"三个独立正式宿主恢复失败：{detail[:240]}；{fallback}"
        ) from exc
    return {
        "status": "restored",
        "mode": "formal",
        "version": version,
        "source_sha256": source_sha256,
        "roles": list(roles),
    }


def 执行宿主切换(switch_id: str) -> None:
    """Run outside managed services; replace admin last and leave durable evidence."""
    state = _读JSON(HOST_SWITCH)
    if state.get("schema") != 1 or state.get("switch_id") != switch_id:
        raise 宿主启动错误("宿主切换记录不匹配")
    target = state.get("target") if isinstance(state.get("target"), dict) else {}
    version = str(target.get("version") or "")
    source_sha256 = str(target.get("source_sha256") or "")
    migration = state.get("mode") == "legacy-migration"
    started_roles: list[str] = []
    try:
        _核对切换仍有效(switch_id)
        _切换状态(
            switch_id,
            status="switching",
            stage="正在切换公司控制和本地精排",
            started_at=state.get("started_at") or time.time(),
            error="",
        )
        # The active pointer can change while the management process is
        # restarting.  Keep this validation inside the recovery boundary so a
        # mismatch still restores the exact pre-switch host snapshot.
        active = 解析活动发布(ACTIVE_LOCK)
        if active["version"] != version or active["source_sha256"] != source_sha256:
            raise 宿主启动错误("活动版本与宿主切换目标不一致")
        if migration:
            if not LEGACY_PLIST.is_file() or LEGACY_PLIST.is_symlink():
                raise 宿主启动错误("旧单进程启动项不存在，无法安全迁移")
            _launchctl("bootout", f"gui/{os.getuid()}", str(LEGACY_PLIST), check=False)
        for role in ("control", "rerank"):
            _核对切换仍有效(switch_id)
            started_at = _启动新角色(role, migration=migration)
            started_roles.append(role)
            _核对切换仍有效(switch_id)
            _等待角色(
                role,
                version=version,
                source_sha256=source_sha256,
                started_at=started_at,
                switch_id=switch_id,
            )
        _核对切换仍有效(switch_id)
        _切换状态(
            switch_id,
            status="switching",
            stage="控制和精排已健康，正在最后更换管理后台",
        )
        _核对切换仍有效(switch_id)
        started_at = _启动新角色("admin", migration=migration)
        started_roles.append("admin")
        _核对切换仍有效(switch_id)
        _等待角色(
            "admin",
            version=version,
            source_sha256=source_sha256,
            started_at=started_at,
            switch_id=switch_id,
        )
        _核对切换仍有效(switch_id)
        _切换状态(
            switch_id,
            status="host-ready",
            stage="三个宿主服务已运行目标正式版本，等待管理后台收口",
            host_ready_at=time.time(),
            fallback="",
        )
        _确认暂存宿主运行面(switch_id)
        # Do not exit while the shared platform and accounts are still being
        # switched.  If management reports a failure, this same helper owns
        # the process-level rollback and starts the sealed fallback.
        _等待管理端收口(switch_id)
    except BaseException as exc:
        # Management recovery or a newer switch may have taken ownership
        # while this detached helper was unwinding.  In either case, touching
        # launchd or starting the fallback here could tear down the new owner.
        if _旧助手应退出(switch_id):
            return
        # Restore the exact pre-switch pointer and launch descriptions before
        # the frozen fallback.  The fallback must never claim the new version
        # when the three-role switch did not become healthy.
        restore_error = ""
        try:
            _恢复暂存宿主运行面(switch_id)
        except BaseException as restore_exc:
            restore_error = f"；旧宿主运行面恢复失败：{str(restore_exc).strip() or type(restore_exc).__name__}"
        try:
            artifact_fallback = _退回未完成正式副本(state)
        except BaseException as artifact_exc:
            artifact_fallback = f"未完成正式副本退回失败：{str(artifact_exc).strip() or type(artifact_exc).__name__}"
            restore_error += f"；{artifact_fallback}"
        # Read the pointer *after* restoration.  Passing the failed target
        # here would make the fallback start old code while waiting for the
        # target identity (and could leave the machine in a false healthy
        # state).
        try:
            fallback_active = 解析活动发布(ACTIVE_LOCK)
            fallback = _恢复冻结正式单进程(
                started_roles,
                version=str(fallback_active["version"]),
                source_sha256=str(fallback_active["source_sha256"]),
            )
        except BaseException as fallback_exc:
            fallback = f"冻结正式单进程恢复失败：{str(fallback_exc).strip() or type(fallback_exc).__name__}"
        _切换状态(
            switch_id,
            status="failed",
            stage="宿主运行面切换失败",
            completed_at=time.time(),
            error=((str(exc).strip() or type(exc).__name__) + restore_error)[:500],
            fallback=fallback,
            artifact_fallback=artifact_fallback,
        )
        raise


def _正式模块路径(role: str, source: Path) -> Path:
    module_name = ROLE_APPLICATIONS[role].partition(":")[0]
    spec = importlib.util.find_spec(module_name)
    origin = Path(str(spec.origin or "")).resolve() if spec is not None else Path()
    if not origin.is_file() or source not in origin.parents:
        raise 宿主启动错误(f"{role} 没有从选定正式源码加载")
    return origin


async def _运行角色进程(role: str) -> None:
    if role not in ROLE_SETTINGS:
        raise 宿主启动错误("宿主服务角色无效")
    source = Path(os.environ.get("XJ_RELEASE_SOURCE", "")).expanduser().resolve()
    version = os.environ.get("XJ_ACTIVE_VERSION", "").strip()
    source_sha256 = os.environ.get("XJ_RELEASE_SOURCE_SHA256", "").strip()
    python_version = os.environ.get("XJ_HOST_PYTHON_VERSION", "").strip()
    dependency_sha256 = os.environ.get("XJ_HOST_DEPENDENCY_SHA256", "").strip()
    if (
        not source.is_dir() or not version or len(source_sha256) != 64
        or not python_version or len(dependency_sha256) != 64
    ):
        raise 宿主启动错误("宿主服务缺少正式运行身份")
    module = _正式模块路径(role, source)
    host_name, port_name, default_port = ROLE_SETTINGS[role]
    host = os.environ.get(host_name, "127.0.0.1")
    try:
        port = int(os.environ.get(port_name, str(default_port)))
    except ValueError as exc:
        raise 宿主启动错误("宿主服务端口无效") from exc
    if host != "127.0.0.1" or not 1024 <= port <= 65535:
        raise 宿主启动错误("宿主服务只允许监听本机高位端口")

    import uvicorn

    server = uvicorn.Server(uvicorn.Config(
        ROLE_APPLICATIONS[role],
        host=host,
        port=port,
        log_level="info",
        proxy_headers=False,
        forwarded_allow_ips="",
    ))
    server.install_signal_handlers = lambda: None
    loop = asyncio.get_running_loop()

    def stop() -> None:
        server.should_exit = True

    for sig in (signal.SIGINT, signal.SIGTERM):
        loop.add_signal_handler(sig, stop)
    base = {
        "role": role,
        "version": version,
        "source": str(source),
        "source_sha256": source_sha256,
        "module": str(module),
        "python_version": python_version,
        "dependency_sha256": dependency_sha256,
        "host": host,
        "port": port,
    }
    _写角色状态({**base, "status": "starting"})
    task = asyncio.create_task(server.serve())
    try:
        while not server.started and not task.done():
            await asyncio.sleep(0.05)
        if server.started:
            _写角色状态({**base, "status": "running"})
        await task
        _写角色状态({**base, "status": "stopped"})
    except BaseException as exc:
        _写角色状态({**base, "status": "failed", "error": type(exc).__name__})
        raise


