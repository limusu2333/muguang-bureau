def _核对唯一开发源(source: Path) -> Path:
    """启动器是独立副本，因此在这里再独立核对一次登记。"""
    source = source.expanduser().resolve()
    record = _读JSON(RUNTIME / "data" / "development-source.json")
    marker = _读JSON(source / ".xj-development-source.json")
    if (
        record.get("schema") != 2
        or Path(str(record.get("source") or "")).expanduser().resolve() != source
        or marker.get("schema") != 1
        or marker.get("kind") != "xiaojiu-canonical-development-source"
        or marker.get("source_id") != record.get("source_id")
        or marker.get("canonical_branch") != record.get("canonical_branch")
    ):
        raise 宿主启动错误("开发管理后台与本机唯一开发源登记不一致")
    result = subprocess.run(
        ["git", "-C", str(source), "branch", "--show-current"],
        stdin=subprocess.DEVNULL, text=True, capture_output=True, check=False,
    )
    if result.returncode != 0 or result.stdout.strip() != record.get("canonical_branch"):
        raise 宿主启动错误("开发管理后台没有运行在唯一开发线")
    store_text = os.environ.get("XJ_RELEASE_STORE", "").strip()
    if store_text:
        store = Path(store_text).expanduser().resolve()
        if source == store or store in source.parents:
            raise 宿主启动错误("封存或候选副本不能启动开发管理后台")
    return source


def 核对三角色入口(source: Path | str) -> dict[str, Any]:
    """静态核对候选源码是否具备三个正式宿主入口。

    这里只检查文件布局，不导入候选源码，也不触碰活动版本、账号或启动项。
    首轮宿主引导必须针对已经固定的候选副本做这项检查，不能拿开发目录代替。
    """
    root = Path(source).expanduser().resolve()
    missing: list[str] = []
    roles: dict[str, dict[str, Any]] = {}
    root_valid = root.is_dir() and not root.is_symlink()
    for role, application in ROLE_APPLICATIONS.items():
        module = application.partition(":")[0]
        path = root.joinpath(*module.split(".")).with_suffix(".py")
        resolved = path.resolve() if path.exists() else path
        present = bool(
            root_valid
            and path.is_file()
            and not path.is_symlink()
            and (resolved == root or root in resolved.parents)
        )
        roles[role] = {
            "module": module,
            "path": str(path),
            "present": present,
        }
        if not present:
            missing.append(role)
    return {
        "ready": root_valid and not missing,
        "source": str(root),
        "roles": roles,
        "missing": missing,
    }


def _正式角色列表(source: Path | str) -> tuple[str, ...]:
    """List host roles present in a sealed source tree.

    Older sealed releases predate optional host components such as local
    rerank. Recovery starts only the roles that release actually contains;
    new candidates still use the strict three-role check above.
    """
    root = Path(source).expanduser().resolve()
    roles: list[str] = []
    for role, application in ROLE_APPLICATIONS.items():
        module = application.partition(":")[0]
        path = root.joinpath(*module.split(".")).with_suffix(".py")
        if path.is_file() and not path.is_symlink() and (path == root or root in path.parents):
            roles.append(role)
    if not {"control", "admin"}.issubset(roles):
        raise 宿主启动错误("封存正式版本缺少控制或管理宿主入口")
    return tuple(roles)


def _读JSON(path: Path) -> dict[str, Any]:
    try:
        value = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise 宿主启动错误(f"活动版本指针无法读取：{path}") from exc
    if not isinstance(value, dict):
        raise 宿主启动错误("活动版本指针格式无效")
    return value


def _写JSON(path: Path, value: Mapping[str, Any]) -> dict[str, Any]:
    path.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
    payload = dict(value)
    fd, temporary = tempfile.mkstemp(prefix=f".{path.name}.", suffix=".tmp", dir=path.parent)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as handle:
            json.dump(payload, handle, ensure_ascii=False, sort_keys=True)
            handle.write("\n")
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(temporary, path)
        path.chmod(0o600)
    finally:
        Path(temporary).unlink(missing_ok=True)
    return payload


def _树指纹(root: Path) -> dict[str, Any]:
    if not root.is_dir() or root.is_symlink():
        raise 宿主启动错误("正式版本源码目录不存在或不是普通目录")
    digest = hashlib.sha256()
    count = 0
    total_size = 0
    for path in sorted(root.rglob("*"), key=lambda item: item.relative_to(root).as_posix()):
        relative = path.relative_to(root)
        if path.is_symlink():
            raise 宿主启动错误(f"正式版本源码不允许符号链接：{relative}")
        if not path.is_file():
            continue
        content = path.read_bytes()
        digest.update(relative.as_posix().encode("utf-8") + b"\0")
        digest.update(b"x" if path.stat().st_mode & 0o111 else b"-")
        digest.update(len(content).to_bytes(8, "big"))
        digest.update(content)
        count += 1
        total_size += len(content)
    return {"sha256": digest.hexdigest(), "files": count, "bytes": total_size}


def _读取清单发布(
    release_path: Path,
    *,
    version: str,
    source_sha256: str,
    allow_staged: bool,
) -> dict[str, Any]:
    raw_release_path = release_path.expanduser()
    if raw_release_path.is_symlink():
        raise 宿主启动错误("活动版本没有指向受控的正式副本")
    try:
        release_path = raw_release_path.resolve(strict=True)
    except OSError as exc:
        raise 宿主启动错误("活动版本的正式副本不存在") from exc
    allowed_parent = {"published", "staged"} if allow_staged else {"published"}
    if (
        not release_path.is_dir()
        or release_path.is_symlink()
        or release_path.name != version
        or release_path.parent.name not in allowed_parent
    ):
        raise 宿主启动错误("活动版本没有指向受控的正式副本")
    manifest = _读JSON(release_path / "manifest.json")
    manifest_source = manifest.get("source") if isinstance(manifest.get("source"), dict) else {}
    manifest_sha = str(manifest_source.get("sha256") or "")
    if (
        manifest.get("version") != version
        or not _SHA256.fullmatch(source_sha256)
        or manifest_sha != source_sha256
    ):
        raise 宿主启动错误("活动版本与正式副本身份不一致")
    source = release_path / "source"
    actual = _树指纹(source)
    if any(actual[key] != manifest_source.get(key) for key in ("sha256", "files", "bytes")):
        raise 宿主启动错误("正式版本源码完整性校验失败，拒绝启动")
    return {
        "version": version,
        "version_name": str(manifest.get("version_name") or version),
        "release_path": str(release_path),
        "source_path": str(source.resolve()),
        "source_sha256": source_sha256,
        "manifest": manifest,
    }


def 解析活动发布(
    active_path: Path = ACTIVE_LOCK,
    *,
    legacy_path: Path | None = None,
) -> dict[str, Any]:
    path = active_path.expanduser().resolve()
    if not path.is_file() and legacy_path is not None and legacy_path.expanduser().is_file():
        path = legacy_path.expanduser().resolve()
    pointer = _读JSON(path)
    version = str(pointer.get("version") or "")
    source = pointer.get("source") if isinstance(pointer.get("source"), dict) else {}
    source_sha256 = str(source.get("sha256") or "")
    if pointer.get("schema") != 3 or not _VERSION.fullmatch(version):
        raise 宿主启动错误("活动版本指针身份无效")
    result = _读取清单发布(
        Path(str(pointer.get("release_path") or "")),
        version=version,
        source_sha256=source_sha256,
        allow_staged=False,
    )
    return {**result, "active_path": str(path)}


def 解析指定发布(
    release_path: Path,
    *,
    version: str,
    source_sha256: str,
    allow_staged: bool = False,
) -> dict[str, Any]:
    if not _VERSION.fullmatch(str(version or "")):
        raise 宿主启动错误("指定宿主版本号无效")
    return _读取清单发布(
        release_path,
        version=version,
        source_sha256=source_sha256,
        allow_staged=allow_staged,
    )


def 解析指定源码(
    source_path: Path,
    *,
    version: str,
    source_sha256: str,
    active_path: Path = ACTIVE_LOCK,
) -> dict[str, Any]:
    """解析固定候选源码供影子验收，绝不改变活动版本指针。"""
    if (
        not _CANDIDATE_VERSION.fullmatch(str(version or ""))
        or not _SHA256.fullmatch(str(source_sha256 or ""))
    ):
        raise 宿主启动错误("影子候选编号或源码指纹无效")
    source = source_path.expanduser().resolve()
    actual = _树指纹(source)
    if actual["sha256"] != source_sha256:
        raise 宿主启动错误("影子候选源码完整性校验失败")
    return {
        "version": version,
        "version_name": version,
        "release_path": str(source.parent),
        "source_path": str(source),
        "source_sha256": source_sha256,
        "active_path": str(active_path.expanduser().resolve()),
        "manifest": {},
    }


def _钥匙串(name: str) -> str:
    result = subprocess.run(
        [
            "/usr/bin/security", "find-generic-password",
            "-s", "xj-multiuser-platform", "-a", name, "-w",
        ],
        stdin=subprocess.DEVNULL,
        text=True,
        capture_output=True,
        check=False,
        timeout=10,
    )
    value = result.stdout.rstrip("\n")
    if result.returncode != 0 or not value or len(value) > 4096 or any(ord(char) < 32 for char in value):
        raise 宿主启动错误(f"宿主启动所需钥匙串配置不可用：{name}")
    return value


def _docker路径() -> str:
    configured = os.environ.get("XJ_DOCKER_BIN", "").strip()
    candidates = (
        Path(configured) if configured else None,
        Path("/opt/homebrew/bin/docker"),
        Path("/usr/local/bin/docker"),
        Path("/Applications/Docker.app/Contents/Resources/bin/docker"),
    )
    for path in candidates:
        if path is not None and path.is_file() and os.access(path, os.X_OK):
            return str(path.resolve())
    found = shutil.which("docker")
    if found:
        return str(Path(found).resolve())
    raise 宿主启动错误("找不到 Docker CLI")


def _冻结摘要() -> str:
    result = subprocess.run(
        [sys.executable, "-m", "pip", "freeze", "--all"],
        stdin=subprocess.DEVNULL,
        text=True,
        capture_output=True,
        check=False,
        timeout=30,
    )
    if result.returncode != 0:
        raise 宿主启动错误("无法核对宿主 Python 依赖")
    lines = sorted(line.strip() for line in result.stdout.splitlines() if line.strip())
    return hashlib.sha256(("\n".join(lines) + "\n").encode("utf-8")).hexdigest()


def 当前运行环境身份() -> dict[str, str | int]:
    return {
        "schema": 1,
        "python_executable": str(Path(sys.executable).resolve()),
        "python_version": platform.python_version(),
        "pip_freeze_sha256": _冻结摘要(),
    }


def 核对运行环境身份(path: Path = RUNTIME_IDENTITY) -> dict[str, str | int]:
    expected = _读JSON(path)
    actual = 当前运行环境身份()
