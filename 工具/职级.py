维持线 = {3: 8.0, 4: 13.0, 5: 18.0}     # 本人真实工作后，工作态信誉掉到该级维持线以下 → 降级
_维持2线 = 1.0     # 正式员工(2)→实习生(1)的线：正常人在种子2受保护够不着；只有砸活穿透保护到底1时、信誉又触底才掉到实习生（触底0后 <1 即真触底）

_锁 = threading.RLock()   # 升降职并发/顶替连锁写状态，串行防盖写（信誉/待验收同类教训）


def _维持门(级: int) -> float:
    return _维持2线 if 级 <= 2 else 维持线.get(级, -9e9)


def 维持不住(人名: str) -> bool:
    """该不该降级。两种情形：
    ① **主动砸活**：近期有偷懒被抓/放水被抓/反复敷衍（不是单次被打回、不是冷清）——种子级也保不住，照降（管理层同理，砸自己活谁也护不了）。
    ② **维持不住**：本人真实工作后，工作态信誉跌破当前级维持线——但**种子级是船主给的底、受保护**，只降到种子级为止。
    种子级以上＝自己挣的，得靠持续信誉守住。经理不豁免：被更强的人顶替(抢坑)照掉、近期砸活照掉，只是不因一周冷清自降。
    2026-07-10 二审改：①从『信任受限』改成『近期有重罚』——分触底0后，冷清也会到受限，不能拿它当主动失败、否则冷清的种子人会被误降。"""
    人名 = str(人名 or "").strip()
    cur = 评级(人名)
    if cur <= 最低级:
        return False
    种子 = _种子表().get(人名, 2)
    底 = max(最低级, 种子)   # 保护底＝种子级；停手冷清最多降回这
    try:
        import 信誉
        if 信誉.有近期重罚(人名):   # ① 主动砸活（偷懒/放水/反复敷衍）：种子保护穿透一级、可掉到种子下一级（丢保护的惩罚，有界）
            底 = max(最低级, 种子 - 1)
    except Exception:  # noqa: BLE001
        pass
    if cur <= 底:   # 已到保护底，不再降（防扫降职的循环把人无限往下拽）
        return False
    return _信誉分(人名) < _维持门(cur)   # ② 信誉跌破当前级维持线才降（种子级受保护、砸活穿透一级）


# ── 存储 ────────────────────────────────────────────────────────────────
def _种子表() -> dict:
    """花名册里各岗位的初始评级：{人名: 评级}。读不到就空。"""
    try:
        r = yaml.safe_load(花名册路径.read_text(encoding="utf-8")) or {}
    except Exception:  # noqa: BLE001
        return {}
    out = {}
    for _岗, c in r.items():
        if isinstance(c, dict) and c.get("名字"):
            try:
                out[str(c["名字"]).strip()] = int(c.get("评级") or 2)
            except (TypeError, ValueError):
                out[str(c["名字"]).strip()] = 2
    return out


def _覆盖表() -> dict:
    return 读JSON(状态文件, 默认={}, 类型=dict) or {}


def _clamp(n: int) -> int:
    return max(最低级, min(最高级, int(n)))


def 评级(人名: str) -> int:
    """这个人此刻的评级（1..5）。覆盖层优先，没有就用花名册种子，再没有默认正式员工(2)。"""
    人名 = str(人名 or "").strip()
    if not 人名:
        return 2
    ov = _覆盖表().get(人名)
    if isinstance(ov, dict) and "评级" in ov:
        try:
            return _clamp(ov["评级"])
        except (TypeError, ValueError):
            pass
    return _clamp(_种子表().get(人名, 2))


def 设评级(人名: str, 新级: int, 原因: str = "") -> int:
    """把某人的评级写进覆盖层（原子写）+ 落变动日志。返回落定后的评级。失败不静默——抛。"""
    人名 = str(人名 or "").strip()
    新级 = _clamp(新级)
    if not 人名:   # L17 二审：空人名直接拒绝，别往状态.json/变动.jsonl 写永远读不回的垃圾键
        return 新级
    with _锁:
        旧 = 评级(人名)
        状态目录.mkdir(parents=True, exist_ok=True)
        表 = _覆盖表()
        表[人名] = {"评级": 新级, "更新": dt.datetime.now().strftime("%Y-%m-%d %H:%M")}
        写JSON(状态文件, 表)
        if 旧 != 新级:
            try:
                with 变动日志.open("a", encoding="utf-8") as f:
                    f.write(json.dumps({
                        "时间": dt.datetime.now().strftime("%Y-%m-%d %H:%M"),
                        "人": 人名, "从": 旧, "到": 新级,
                        "动作": ("升职" if 新级 > 旧 else "降职"),
                        "原因": (原因 or "").strip()[:80],
                    }, ensure_ascii=False) + "\n")
            except Exception:  # noqa: BLE001 日志失败不拖累状态本身
                pass
            try:   # 评级一变（升/降/顶替/船主手调），晋升曲线归零——在新级别从头爬
                import 晋升
                晋升.清曲线(人名)
            except Exception:  # noqa: BLE001
                pass
    return 新级


def 职称(人名: str) -> str:
    """可读职称＝级名（部门主管带部门名）。1实习生 2正式员工 3<部门>主管 4副经理 5经理。
    3L6 三审：谁此刻是现任经理就显示『经理』——即使唯一的5级被顶下、公司最高只剩4级，顶上者握审批权、身份就是经理。"""
    if 是经理(人名):
        return "经理"
    n = 评级(人名)
    if n == 主管级:
        d = _人的部门目录名(人名)
        return f"{d}主管" if d else "部门主管"
    return 级名[n - 1]


# ── 职能/部门（跟人不变；只有调任才动）────────────────────────────────────
# 3M2 三审：统一走 部门.认领部门（它认调任覆盖）——否则调任后"同部门/部门头/抢坑对象"这里读花名册岗位、和记忆/权限那边打架。
def _人的部门目录名(人名: str) -> str | None:
    try:
        import 部门
        d = 部门.认领部门(人名)
        return getattr(d, "目录名", None) if d is not None else None
    except Exception:  # noqa: BLE001
        return None


def _同部门的人(人名: str) -> list[str]:
    """和这个人此刻同部门的所有人（含自己）的人名——按 部门.认领部门 分组（认调任覆盖）。单人部门就返回他自己。"""
    try:
        import 部门
        import 模型接入
        本 = 部门.认领部门(人名)
        if 本 is None:
            return [str(人名 or "").strip()] if str(人名 or "").strip() else []
        出 = []
        for c in 模型接入.花名册().values():
            n = str((c or {}).get("名字") or "").strip()
            if n and 部门.认领部门(n) is 本:
                出.append(n)
        return sorted(set(出)) or [str(人名 or "").strip()]
    except Exception:  # noqa: BLE001
        return [str(人名 or "").strip()]


# ── 权限解析（按评级动态定谁是头/谁是经理）──────────────────────────────
def _信誉分(人名: str) -> float:
    try:
        import 信誉
        return 信誉.工作态信誉分(人名)
    except Exception:  # noqa: BLE001
        return 0.0


def 部门头(人名: str) -> str | None:
    """这个人所在部门此刻的头＝部门里(评级, 信誉)最高的人——**但必须达到主管级(≥3)**，否则无头（返回 None）。
    2026-07-10 二审(F6)：无人达主管级时不该靠列表顺序钦定一个普通员工当头去审同僚/派活；无头就走单人/直接进验收路径。
    单人部门里那个人若达主管级＝他自己是头；没达＝无头（本就跳过把关，和单人一样）。"""
    人 = str(人名 or "").strip()
    同 = _同部门的人(人)
    if not 同:
        return None
    顶 = max(同, key=lambda p: (评级(p), _信誉分(p)))
    return 顶 if 评级(顶) >= 主管级 else None


def 现任经理() -> str | None:
    """全公司握审批权的人＝**评级最高的人**（并列比信誉）。经理不存在真空：谁在顶上谁就是经理（船主 2026-07-10）。"""
    try:
        import 模型接入
        人们 = [c["名字"] for c in 模型接入.花名册().values() if isinstance(c, dict) and c.get("名字")]
    except Exception:  # noqa: BLE001
        return None
    if not 人们:
        return None
    return max(人们, key=lambda p: (评级(p), _信誉分(p)))


def 是经理(人名: str) -> bool:
    """谁在顶上谁就是经理——统一走现任经理()，不再另加『评级=5』的门（2026-07-10 二审：那个多余的门会让被降级的顶上者
    在一处被当经理、另一处被当普通员工，两套身份打架、甚至自审自放。经理不存在真空、顶上者永远是经理）。"""
    人名 = str(人名 or "").strip()
    return bool(人名) and 现任经理() == 人名


# ── 升 / 降 / 扫描（信誉驱动 + 管理坑限量抢占）──────────────────────────
def _本部门现任主管(人名: str, 除self: bool = True) -> str | None:
    """人所在部门里『恰好在主管级』的人里信誉最高的（默认排掉自己）。没有返回 None。
    2026-07-10 二审：只认『==主管级』、不含更高级——部门里的副经理/经理在主管之上、不占主管坑，不该被升主管的人顶替砸穿。"""
    候选 = [p for p in _同部门的人(人名) if 评级(p) == 主管级 and (not 除self or p != 人名)]
    if not 候选:
        return None
    return max(候选, key=_信誉分)


def 升(人名: str) -> dict | None:
    """把某人升一级。返回 {人,从,到,被顶,说明} 或 None（升不动：到顶/满坑没赢过现任）。
    坑规则：目标<主管级不占坑达标即升；=主管级要本部门坑空或信誉赢过现任主管；=经理级要坑空或赢过现任经理。"""
    with _锁:
        人名 = str(人名 or "").strip()
        cur = 评级(人名)
        if cur >= 最高级:
            return None
        目标 = cur + 1
        # 3H1 三审：升到某级前，信誉必须够得着这级的维持线——climb 得起才能上，否则升完立刻被扫降职打回来、还清空刚攒满的晋升曲线。
        # 晋升曲线(晋升分)管"够不够格上"，信誉维持线管"守不守得住"，两者都过才真升，避免升降在同一次验收里打架。
        if _信誉分(人名) < _维持门(目标):
            return None
        # 硬坑只有两个：部门主管(3，每部门1)、经理(5，全公司1)。其余(→2正式员工、→4副经理)不占坑、达标即升。
        if 目标 == 主管级:
            现任 = _本部门现任主管(人名)   # 本部门评级≥主管级的人里信誉最高者(排掉自己)
            if 现任 is None:
                设评级(人名, 目标, "晋升部门主管·坑空")
                return {"人": 人名, "从": cur, "到": 目标, "被顶": None, "说明": f"{人名} 晋升{职称(人名)}"}
            if _信誉分(人名) > _信誉分(现任):
                设评级(现任, 评级(现任) - 1, f"被 {人名} 顶替，降一级")   # 顶替只降现任一级（现任==主管级、降到正式员工），不写死砸穿
                设评级(人名, 目标, f"晋升部门主管，顶替 {现任}")
                return {"人": 人名, "从": cur, "到": 目标, "被顶": 现任, "说明": f"{人名} 晋升部门主管，顶下 {现任}"}
            return None   # 够线但没赢过现任主管，坑没让出，不升
        if 目标 == 经理级:
            现任 = 现任经理()
            if 现任 in (None, 人名) or 评级(现任) < 经理级:
                设评级(人名, 目标, "升任经理·坑空")
                return {"人": 人名, "从": cur, "到": 目标, "被顶": None, "说明": f"{人名} 升任经理"}
            if _信誉分(人名) > _信誉分(现任):
                设评级(现任, 评级(现任) - 1, f"被 {人名} 顶替，降一级")   # 顶替只降一级
                设评级(人名, 目标, f"升任经理，顶替 {现任}")
                return {"人": 人名, "从": cur, "到": 目标, "被顶": 现任, "说明": f"{人名} 升任经理，顶下 {现任}"}
            return None
        # 目标 == 2(正式员工) 或 4(副经理)：不占硬坑，达标即升
        设评级(人名, 目标, "达标晋升·不占管理坑")
        return {"人": 人名, "从": cur, "到": 目标, "被顶": None, "说明": f"{人名} 升为{级名[目标-1]}"}


def 降(人名: str) -> dict | None:
    """把某人降一级。返回 {人,从,到,说明} 或 None（已在最低级）。"""
    with _锁:
        人名 = str(人名 or "").strip()
        cur = 评级(人名)
        if cur <= 最低级:
            return None
        目标 = cur - 1
        设评级(人名, 目标, "信誉掉到降职线")
        return {"人": 人名, "从": cur, "到": 目标, "被顶": None, "说明": f"{人名} 降为{级名[目标-1]}"}


def 扫降职(触发人: str | None = None) -> list[dict]:
    """全员扫一遍『维持不住』的，降级（升职是事件驱动的、走晋升曲线，不在这）。
    触发人给了只看他，否则全员扫。返回本次降级变动，交上层公告。"""
    try:
        import 模型接入
        人们 = [触发人.strip()] if 触发人 else [
            c["名字"] for c in 模型接入.花名册().values() if isinstance(c, dict) and c.get("名字")
        ]
    except Exception:  # noqa: BLE001
        return []
    变动: list[dict] = []
    for 人 in [p for p in 人们 if p]:
        try:
            守 = 0
            while 维持不住(人) and 守 < 最高级:   # 一次扫到位：连着降到不再维持不住的那级（有界防死循环）
                r = 降(人)
                守 += 1
                if not r:
                    break
                变动.append(r)
        except Exception:  # noqa: BLE001
            pass
    return 变动
    # 2026-07-10 二审：改成 while 一次降到位——原来每次别人验收触发只降1级，一波突发验收会把人连降好几级、
    # 掉几级取决于别人多忙而非他自己（不公）。现在无论触发几次，都稳定降到信誉对应的那级为止。


