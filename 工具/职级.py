def 调任(人名: str, 目标部门目录名: str) -> dict:
    """把人平级调到另一个部门（换职能、评级不变）。返回 {ok, 说明}。评级不动（升降职才动评级）。
    2026-07-10 二审加固：
    - **H5 校验**：目标必须是真部门，否则拒绝、不搬文件不落覆盖（防拼错把记忆搬进幽灵目录、人退回空旧部门）。
    - **H4 原子/可恢复**：先『搬记忆(原子 tmp+replace)』再『落覆盖』——搬失败就不落覆盖、状态没变可重跑；
      即使落覆盖前崩，文件已在新部门、重跑同一调任即恢复（源算成旧部门、搬发现'已在'、补落覆盖）。"""
    import 部门
    from 记忆迁移 import 迁移个人记忆   # 延迟导入，避免环
    人名 = str(人名 or "").strip()
    目标 = str(目标部门目录名 or "").strip()
    有效部门 = {getattr(d, "目录名", None) for d in 部门.各部门()}
    if not 人名:
        return {"ok": False, "说明": "调任失败：空人名"}
    if 目标 not in 有效部门:   # H5
        现有 = "、".join(sorted(x for x in 有效部门 if x))
        return {"ok": False, "说明": f"调任失败：『{目标}』不是有效部门（现有：{现有}）——没搬文件、没改归属"}
    with _锁:
        源目录 = 部门.部门目录(人名)      # 覆盖生效前的旧部门目录（迁移要用它当源）
        旧部门名 = 源目录.name
        if 旧部门名 == 目标:
            return {"ok": True, "说明": f"{人名} 已在 {目标}，无需调任"}
        结果 = 迁移个人记忆(人名, 源目录, 目标)   # ① 先搬（原子；若抛异常，下面落覆盖不会执行＝回滚）
        状态目录.mkdir(parents=True, exist_ok=True)   # ② 搬成功再落覆盖
        表 = 读JSON(调任覆盖文件, 默认={}, 类型=dict) or {}
        表[人名] = 目标
        写JSON(调任覆盖文件, 表)
        try:
            with 变动日志.open("a", encoding="utf-8") as f:
                f.write(json.dumps({
                    "时间": dt.datetime.now().strftime("%Y-%m-%d %H:%M"),
                    "人": 人名, "动作": "调任", "从部门": 旧部门名, "到部门": 目标,
                    "评级": 评级(人名), "迁记忆": 结果,
                }, ensure_ascii=False) + "\n")
        except Exception:  # noqa: BLE001
            pass
    return {"ok": True, "说明": f"{人名} 平级调任 {旧部门名}→{目标}（评级{评级(人名)}不变；{结果}）"}


