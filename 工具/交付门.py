#!/usr/bin/env python3
"""交付审核链：解析制式批文并执行部门、独立、经理三道复核。"""
from __future__ import annotations

import datetime as dt
import re


def _可参与岗位() -> set[str]:
    import 模型接入

    roles = {str(name) for name in 模型接入.花名册().keys() if str(name).strip()}
    if not roles:
        raise RuntimeError("花名册为空，拒绝使用固定旧岗位绕行")
    return roles


_噪 = "*_#>`~- \t　\"'「」『』“”‘’（）()【】[]〔〕"   # 取『值』时剥掉的噪声（含强方括号）
# 行级去噪**故意不含强方括号【】[]〔〕**——方括号要留着给"是不是真填了结论栏"做判据（九审：裸『结论：放行』回显不作准、带方括号才认放行）；
# markdown/引号/圆括号/空白照剥，免得 **【结论】放行** 前后的记号碍事。
_行噪 = "*_#>`~- \t　\"'「」『』“”‘’（）()"
_尾标点 = "。.！!？?，,、；;：: 　"
_结论头re = re.compile(r"^([【\[〔])?\s*结论\s*[】\]〕]?\s*[:：]?\s*(.*)$")   # group1=开头强方括号(有=真填栏)，group2=值
_理由头re = re.compile(r"^[【\[〔]?\s*理由\s*[】\]〕]?\s*[:：]?\s*(.*)$")
_判词 = ("放行", "打回")


def _净判词值(片: str) -> str:
    """结论/理由栏的值剥掉噪声与尾标点，返回收干净后的字符串（可能是精确判词、也可能是脏值或空）。"""
    return str(片 or "").strip(_噪).strip(_尾标点).strip(_噪)


def _审结果(评审) -> tuple:
    """读审核人的『制式批文』：逐行找【结论】栏、**只认整体精确等于『放行/打回』**，理由随它写、一个字不猜自然语言。
    最严原则（八审后定稿）：任何『不干净』一律 → 判不清（安全兜底、重审），绝不放水也不冤枉——
    ①结论栏写脏/写成句子/夹别的字（哪怕另有一条干净放行栏）→ 判不清，不让干净放行独赢（八审F1）；
    ②整篇没有【结论】栏时，只认『整篇每行都是裸判词』的老实首行式；有散文/理由行就判不清，绝不在散文/理由里捞孤立判词（八审F2）；
    ③放行**必须带强方括号**【结论】放行才认——裸『结论：放行』极可能是照抄示例的回显、正文却在真拒绝，判它放行=放水（九审）；打回带不带方括号都认（安全方向）；
    ④有一栏干净『打回』→ 打回（安全方向先判）。空/失败标记 → 审崩。
    残余（船主知情）：审核人若**主动**写下带方括号的【结论】放行、正文却又矛盾地拒绝，本函数按契约信任该栏=放行（读字段、不猜正文，同『审批』线）；这块靠提示词约束+架构（结构化输出）根治，非解析器能判。
    返回 (放行/打回/判不清/审崩, 附言)：打回=理由，放行=给下游的评语。"""
    s = str(评审 or "").strip()
    if (not s) or ("已停。要重跑说一声" in s):   # 唤醒本人 超时/欠费/断流的失败标记
        return "审崩", ""
    行 = [x for x in (ln.strip().strip(_行噪) for ln in s.splitlines()) if x]
    结论clean: list[str] = []   # 值精确等于放行/打回 的【结论】栏
    有脏结论 = 有理由栏 = False
    理由 = ""
    for c in 行:
        if m := _结论头re.match(c):
            v = _净判词值(m.group(2))
            if v == "打回":
                结论clean.append("打回")        # 打回：安全方向，带不带强方括号都认
            elif v == "放行" and m.group(1):    # 放行：**必须带强方括号【】/[]/〔〕**才认——裸"结论：放行"极可能是照抄示例的回显，正文却在真拒绝，判它放行=放水（九审）
                结论clean.append("放行")
            elif v:                             # 裸"结论：放行" / 写脏 / 写成句子 → 不作准（→判不清，除非另有干净打回）
                有脏结论 = True
            continue
        if mr := _理由头re.match(c):
            有理由栏 = True
            if not 理由:
                理由 = _净判词值(mr.group(1))[:120]
    if "打回" in 结论clean:          # 有干净打回栏 → 打回（安全方向先判）
        return "打回", 理由 or "（没说明理由）"
    if 有脏结论:                     # 有结论栏但没写成精确判词 → 没说清，判不清（别让同篇一条干净放行独赢）
        return "判不清", ""
    if "放行" in 结论clean:
        return "放行", 理由
    # 到这：整篇没有任何【结论】栏。有理由栏却没结论栏＝半制式说不清 → 判不清；
    # 否则只认『老实首行式』——整篇每一行都是裸判词才认（有散文/杂行就判不清，绝不在散文里捞孤立判词）。同样有打回则打回。
    if 有理由栏 or not 行 or any(c.rstrip(_尾标点) not in _判词 for c in 行):
        return "判不清", ""
    裸 = {c.rstrip(_尾标点) for c in 行}
    return ("打回", "（没说明理由）") if "打回" in 裸 else ("放行", "")


async def _过交付门(被派岗位: str, 任务: str, 产出: str):
    """交付门（D）：被派人的产出先过部门复核；本人是部门头/单人部门时必须换独立替补。
    返回 (通过:bool, 文案:str, 放行人人名:str|None, 节点)。任何内部异常都拒绝放行并留下可见节点。"""
    try:
        import 部门
        from 活_本人 import 唤醒本人, _progress_var, _岗位的人, 给某人记一笔
        被派人 = _岗位的人(被派岗位)
        头人名 = 部门.部门头(被派人)
        头岗位 = 部门._人名到岗位(头人名) if 头人名 else None
        代理 = False
        if not 头岗位 or not 头人名 or 头人名 == 被派人:
            头岗位, 头人名 = 部门.部门复核替补(被派人, 排除人名=[被派人])
            代理 = True
        if not 头岗位 or not 头人名:
            节点 = {
                "时间": dt.datetime.now().strftime("%Y-%m-%d %H:%M"),
                "层级": "部门复核", "谁": "系统", "动作": "无独立复核人·未放行",
            }
            return False, "【部门头与交付人冲突，且没有可用独立替补；交付已拦住，不能跳过部门复核】", None, 节点
        身份 = "部门复核替补" if 代理 else "本部门的头"
        提示 = (
            f"你是{头岗位}（{身份}），审『{被派岗位}』刚交付的活，把部门这道关。\n"
            f"任务：{任务}\n\n他的产出：\n{产出}\n\n"
            f"判定能不能放行上交，按**制式批文**回，就两行：\n"
            f"【结论】放行　（不行就写：【结论】打回）\n"
            f"【理由】一句话（打回必写哪儿不行；放行可写亮点或提醒，没有就写「无」）\n"
            f"硬要求：①『结论』那行**必须带方括号**写成 【结论】放行 或 【结论】打回，**只填一个词**、别写成句子、别夹别的字；"
            f"②你的**真实判定就写在结论栏**——别把上面的示例照抄一遍、别在正文里另说一套；要打回就写【结论】打回，别嘴上打回却把结论栏填成放行。"
        )
        评审 = await 唤醒本人(头岗位, 提示, progress=_progress_var.get())
        _ts = dt.datetime.now().strftime("%Y-%m-%d %H:%M")
        结果, 附 = _审结果(评审)
        if 结果 in ("审崩", "判不清"):   # 别静默：审核人模型崩了/没给明确结论——绝不当放行，留可见节点、不记谁信誉（不是被派人的错）
            由 = "评审模型崩了/没返回" if 结果 == "审崩" else "没给明确放行/打回结论"
            节点 = {"时间": _ts, "层级": "部门复核", "谁": 头人名, "动作": f"审出错·未放行（{由}）"}
            return False, f"【{被派岗位} 的活没审成：部门头（{头岗位}）{由}、未放行，要重审说一声（不是他的错，本次不记信誉）】\n\n原产出：\n{产出}", None, 节点
        if 结果 == "打回":
            理由 = 附
            try:
                给某人记一笔(被派人, f"[部门头打回] {任务.strip()[:60]}｜理由：{理由}")
            except Exception:  # noqa: BLE001
                pass
            try:
                import 信誉
                信誉.记打回(被派人, f"部门头打回：{理由[:40]}", 把关者=头人名)   # 反复被打回自动追记『反复敷衍』；落把关者供平反精确定位(十审#3)
            except Exception:  # noqa: BLE001
                pass
            节点 = {"时间": _ts, "层级": "部门复核", "谁": 头人名, "动作": f"{'代理' if 代理 else ''}审 → 打回「{理由}」"}
            return False, f"【{被派岗位} 的活被部门头（{头岗位}）打回，未进验收】理由：{理由}\n\n原产出：\n{产出}", None, 节点
        评语 = 附
        try:
            if 评语:
                给某人记一笔(被派人, f"[部门头放行·评语] {任务.strip()[:50]}｜{评语}")
        except Exception:  # noqa: BLE001
            pass
        节点 = {"时间": _ts, "层级": "部门复核", "谁": 头人名, "动作": ("代理审" if 代理 else "审") + " → 放行" + (f"「{评语}」" if 评语 else "")}
        return True, f"部门复核（{头岗位}{'·独立替补' if 代理 else ''}）已放行" + (f"，评语：{评语}" if 评语 else ""), 头人名, 节点
    except Exception as e:  # noqa: BLE001
        节点 = {
            "时间": dt.datetime.now().strftime("%Y-%m-%d %H:%M"),
            "层级": "部门头", "谁": "部门头",
            "动作": f"把关故障·未放行（{type(e).__name__}）",
        }
        return False, f"【部门头把关环节内部故障，交付已拦住、没有跳过】{type(e).__name__}: {e}", None, 节点


async def _过独立复核(被派岗位: str, 任务: str, 产出: str):
    """信誉受限时增加一次独立复核。它只会加一道门，绝不会替代部门头、经理或船主。"""
    try:
        from 活_本人 import 唤醒本人, _progress_var, _岗位的人
        import 信誉

        被派人 = _岗位的人(被派岗位)
        if not 信誉.需加复核(被派人):
            return True, "", None, None
        候选 = [g for g in ("测试工程师", "首席工程师") if g != 被派岗位 and g in _可参与岗位()]
        if not 候选:
            节点 = {"时间": dt.datetime.now().strftime("%Y-%m-%d %H:%M"), "层级": "独立复核", "谁": "系统", "动作": "无可用独立复核人·未放行"}
            return False, "【信誉受限需增加独立复核，但当前没有可用的独立复核岗位，交付已拦住】", None, 节点
        复核岗 = 候选[0]
        提示 = (
            f"你现在做一次独立复核。被复核人：{被派人}（{被派岗位}）。\n"
            f"任务：{任务}\n\n产出：\n{产出}\n\n"
            "只核事实、要求和明显风险，不替代部门头或经理。按两行制式批文回答：\n"
            "【结论】放行 或 【结论】打回\n【理由】一句话。"
        )
        回 = await 唤醒本人(复核岗, 提示, progress=_progress_var.get())
        结果, 理由 = _审结果(回)
        复核人 = _岗位的人(复核岗)
        ts = dt.datetime.now().strftime("%Y-%m-%d %H:%M")
        if 结果 == "放行":
            节点 = {"时间": ts, "层级": "独立复核", "谁": 复核人, "动作": "复核 → 放行" + (f"「{理由}」" if 理由 else "")}
            return True, f"独立复核（{复核岗}）已放行" + (f"，说明：{理由}" if 理由 else ""), 复核人, 节点
        if 结果 == "打回":
            节点 = {"时间": ts, "层级": "独立复核", "谁": 复核人, "动作": f"复核 → 打回「{理由}」"}
            return False, f"【独立复核打回，未上经理】理由：{理由}\n\n原产出：\n{产出}", 复核人, 节点
        由 = "复核模型崩了/没返回" if 结果 == "审崩" else "没给明确结论"
        节点 = {"时间": ts, "层级": "独立复核", "谁": 复核人, "动作": f"复核故障·未放行（{由}）"}
        return False, f"【独立复核没审成：{由}，交付已拦住】", 复核人, 节点
    except Exception as e:  # noqa: BLE001
        节点 = {"时间": dt.datetime.now().strftime("%Y-%m-%d %H:%M"), "层级": "独立复核", "谁": "系统", "动作": f"复核故障·未放行（{type(e).__name__}）"}
        return False, f"【独立复核环节内部故障，交付已拦住】{type(e).__name__}: {e}", None, 节点


async def _过经理收敛(任务: str, 产出: str, 派活人名: str, 被派人名: str, 已复核人名: str = ""):
    """经理收敛门（②）：部门头放行后、上船主前，交付先过经理（老钟）收敛整合，放行才上船主验收。
    谁派活都必须收敛；经理本人交付或经理已在上一层复核时，换独立代理经理，不能自审或跳过。"""
    try:
        import 部门
        import 职级
        import 经理代理

        临时岗, 临时名 = 经理代理.当前临时统筹()
        经理名 = 临时名 or 职级.现任经理()
        经理岗 = 临时岗 or (部门._人名到岗位(经理名) if 经理名 else None)
        _ts0 = dt.datetime.now().strftime("%Y-%m-%d %H:%M")
        if not 经理岗 or not 经理名:
            节点 = {"时间": _ts0, "层级": "经理", "谁": "系统", "动作": "经理缺位·未放行"}
            return False, "【经理收敛口缺位，交付已拦住，不能越级上船主】", None, 节点
        代理 = bool(临时名) or 经理名 in {(被派人名 or "").strip(), (已复核人名 or "").strip()}
        if 代理:
            if 临时名:
                经理岗, 经理名 = 临时岗, 临时名
            else:
                经理岗, 经理名 = 部门.经理复核替补(排除人名=[被派人名, 已复核人名])
                if not 经理岗 or not 经理名:
                    节点 = {"时间": _ts0, "层级": "经理", "谁": "系统", "动作": "无独立代理经理·未放行"}
                    return False, "【经理与交付人或上一层复核人冲突，且没有独立代理经理；交付已拦住】", None, 节点
        from 活_本人 import 唤醒本人, _progress_var, 给某人记一笔
        提示 = (
            f"你是{经理岗}（{'代理经理复核' if 代理 else '对船主的收敛口'}）。部门复核已放行『{被派人名}』这份交付，现在到你做**交付前审查**、决定能不能上船主。\n"
            f"任务（当初提的要求，就是验收标准）：{任务}\n\n产出：\n{产出}\n\n"
            f"逐条对照任务当初的要求核一遍：①要求都满足了吗　②范围对不对（该做的做了没、有没有多做/漏做）　③质量达标、拿得出手吗。\n"
            f"**达标才放行**——你只做质量控制，最终算不算数是船主验收拍板。\n"
            f"按**制式批文**回，就两行：\n"
            f"【结论】放行　（不行就写：【结论】打回）\n"
            f"【理由】一句话（打回必写哪条没达标；放行写给船主的交接说明——对着哪条要求做的、要看啥，没有就写「无」）\n"
            f"硬要求：①『结论』那行**必须带方括号**写成 【结论】放行 或 【结论】打回，**只填一个词**、别写成句子、别夹别的字；"
            f"②你的**真实判定就写在结论栏**——别把上面的示例照抄一遍、别在正文里另说一套；要打回就写【结论】打回，别嘴上打回却把结论栏填成放行。"
        )
        回 = await 唤醒本人(经理岗, 提示, progress=_progress_var.get())
        _ts = dt.datetime.now().strftime("%Y-%m-%d %H:%M")
        结果, 附 = _审结果(回)
        if 结果 in ("审崩", "判不清"):   # 别静默：经理模型崩了/没给明确结论——绝不当放行，留可见节点、不记信誉
            由 = "评审模型崩了/没返回" if 结果 == "审崩" else "没给明确放行/打回结论"
            节点 = {"时间": _ts, "层级": "经理", "谁": 经理名, "动作": f"审出错·未放行（{由}）"}
            return False, f"【{被派人名}的交付没审成：经理（{经理岗}）{由}、未上船主，要重审说一声（不是他的错，本次不记信誉）】\n\n原产出：\n{产出}", None, 节点
        if 结果 == "打回":
            理由 = 附
            try:
                给某人记一笔(被派人名, f"[经理收敛打回] {任务.strip()[:60]}｜{理由}")
            except Exception:  # noqa: BLE001
                pass
            try:
                import 信誉
                信誉.记打回(被派人名, f"经理收敛打回：{理由[:40]}", 把关者=经理名)   # 反复被打回自动追记『反复敷衍』；落把关者供平反精确定位(十审#3)
            except Exception:  # noqa: BLE001
                pass
            节点 = {"时间": _ts, "层级": "经理", "谁": 经理名, "动作": f"收敛 → 打回「{理由}」"}
            return False, f"【{被派人名}的交付被经理（{经理岗}）收敛时打回，未上船主验收】理由：{理由}\n\n原产出：\n{产出}", None, 节点
        交接 = 附
        节点 = {"时间": _ts, "层级": "经理", "谁": 经理名, "动作": ("代理收敛" if 代理 else "收敛") + " → 放行" + (f"「{交接}」" if 交接 else "")}
        return True, f"{'代理经理复核' if 代理 else '经理'}（{经理岗}）已收敛放行" + (f"，交接：{交接}" if 交接 else ""), 经理名, 节点
    except Exception as e:  # noqa: BLE001
        节点 = {
            "时间": dt.datetime.now().strftime("%Y-%m-%d %H:%M"),
            "层级": "经理", "谁": "经理",
            "动作": f"收敛故障·未放行（{type(e).__name__}）",
        }
        return False, f"【经理收敛环节内部故障，交付已拦住、没有越级】{type(e).__name__}: {e}", None, 节点
