#!/usr/bin/env python3
"""死平台 · 大厅责任席。

大厅只决定“谁先对这句话负责”：点名直达，明确承接者续接，否则项目经理接。
说什么、要不要问同事、是否转交、是否进入正式工作，都由真正听见的人判断。

这里不调意图判定模型，不用常识门打分，也不从发言文字猜谁应该接班。
不可逆操作的确认门仍在各自的工具/审批边界，不属于大厅路由。
"""
from __future__ import annotations

import asyncio

import 事件总线
import 大厅记录
from 实例配置 import 主人称呼
import 经理代理


默认上下文窗口 = 12


def 当前责任岗位(房间键: str = "大厅") -> str:
    """返回这一场的逻辑责任席。状态/花名册故障都回项目经理，不堵住用户发言。"""
    try:
        岗位 = 大厅记录.当前承接岗位(房间键)
        if not 岗位:
            return "项目经理"
        from 平台_工具集 import 可参与岗位
        return 岗位 if 岗位 in 可参与岗位() else "项目经理"
    except Exception:  # noqa: BLE001
        return "项目经理"


def _记责任席(岗位: str, 房间键: str, 原因: str, 进度) -> None:
    try:
        大厅记录.记承接岗位(岗位, 房间键, 原因)
    except Exception as e:  # noqa: BLE001
        # 责任席是下一轮的路由参考，不能因它落盘失败吞掉已经说出的话。
        进度(f"大厅责任席未能记住（{type(e).__name__}）；下轮会回项目经理接，本轮回话不受影响。")


async def _唤醒统筹(原岗位: str, 来意: str, *, progress, 会话id: str, 失败原因: str = "") -> tuple[str, str]:
    """唤醒经理责任席：原经理优先，失败时由现有临时经理租约接管。"""
    from 活_本人 import 唤醒本人, _岗位的人 as _人

    key = str(会话id or "大厅")
    try:
        回 = await 唤醒本人(原岗位, 来意, progress=progress, 会话id=会话id)
        经理代理.清租约(key)
        return 原岗位, 回
    except Exception as e:  # noqa: BLE001
        cause = 失败原因 or f"{_人(原岗位)}未能到岗：{type(e).__name__}: {e}"
        租 = 经理代理.确保租约(key, 原岗位=原岗位, 排除岗位=[原岗位], 原因=cause)
        代理岗 = str(租["代理岗位"])
        progress(
            f"{_人(原岗位)}未能到岗，本单由{租['代理人']}（{代理岗}）临时代理统筹；"
            "这不是升职，原经理下一单能到岗就自动恢复。"
        )
        提示 = (
            f"{来意}\n\n"
            f"【临时代理经理租约】{_人(原岗位)}这次未能到岗；本单由你临时承接统筹。"
            "这不是职级晋升，不改公司职级账；本单只能有你一个统筹口。"
            f"你要按项目经理职责做立项、拆分、派活、会议和收敛，仍走部门复核、经理收敛、{主人称呼()}验收链。"
            "原经理恢复后，新任务自动回归原经理。"
        )
        tok = 经理代理.进入临时统筹(租)
        try:
            回 = await 唤醒本人(代理岗, 提示, progress=progress, 会话id=会话id)
        finally:
            经理代理.退出临时统筹(tok)
        return 代理岗, 回


async def _唤醒聊天统筹(
    原岗位: str,
    本轮已说: list[tuple[str, str]],
    *,
    progress,
    会话id: str,
    上下文窗口: int = 默认上下文窗口,
    唤醒理由: str = "",
    聊天动作: dict | None = None,
    复核提醒: bool = False,
) -> tuple[str, str]:
    """经理责任席的聊天唤醒：原经理不可用时，临时经理直接坐进同一席位。"""
    from 活_本人 import 聊天唤醒, 聊天预算已满, _岗位的人 as _人

    key = str(会话id or "大厅")
    try:
        回 = await 聊天唤醒(
            原岗位,
            本轮已说,
            会话id=会话id,
            progress=progress,
            上下文窗口=上下文窗口,
            唤醒理由=唤醒理由,
            聊天动作=聊天动作,
            复核提醒=复核提醒,
        )
        经理代理.清租约(key)
        return 原岗位, 回
    except Exception as e:  # noqa: BLE001
        if isinstance(e, 聊天预算已满):
            raise
        租 = 经理代理.确保租约(
            key,
            原岗位=原岗位,
            排除岗位=[原岗位],
            原因=f"{_人(原岗位)}聊天接待未能到岗：{type(e).__name__}: {e}",
        )
        代理岗 = str(租["代理岗位"])
        progress(
            f"{_人(原岗位)}聊天接待未能到岗，本轮由{租['代理人']}（{代理岗}）临时代理；"
            "这不是升职，原经理下一轮能到岗就自动恢复。"
        )
        if isinstance(聊天动作, dict):
            聊天动作.clear()
        tok = 经理代理.进入临时统筹(租)
        try:
            回 = await 聊天唤醒(
                代理岗,
                本轮已说,
                会话id=会话id,
                progress=progress,
                上下文窗口=上下文窗口,
                唤醒理由=(
                    f"你正临时坐在项目经理责任席：{唤醒理由}。"
                    "这不是升职，但本轮你要对大厅回话负责。"
                ),
                聊天动作=聊天动作,
                复核提醒=复核提醒,
            )
        except Exception as proxy_error:  # noqa: BLE001
            progress(f"临时代理{_人(代理岗)}也未能接住本轮聊天。")
            raise RuntimeError(f"{_人(原岗位)}和临时代理{_人(代理岗)}都未能接住大厅聊天") from proxy_error
        finally:
            经理代理.退出临时统筹(tok)
        return 代理岗, 回


def _是发言(回: str) -> bool:
    回 = str(回 or "").strip()
    return bool(回) and 回 not in ("[沉默]", "[转办事]", "（没说话）") and "[沉默]" not in 回


def _落一句(实际岗位: str, 回: str, sid: str, 本场发言, *, 发群聊事件: bool) -> tuple[str, str]:
    from 活_本人 import _岗位的人 as _人

    回 = str(回 or "").strip()
    人 = _人(实际岗位)
    if 发群聊事件:
        事件总线.发布事件(sid, {"类型": "群聊发言", "发言人": 人, "内容": 回})
    大厅记录.记一句(人, 回, 事件键=大厅记录.发言事件键(sid, 人, 回))
    本场发言.append((人, 实际岗位, 回))
    return 人, 回


async def 活厅(
    原话,
    sid,
    进度,
    本场发言,
    会里的人,
    目标岗位,
    被点名,
    原文,
    text,
    房间键: str = "大厅",
):
    """大厅一轮：一个责任人先听见，只有他明确询问/邀请/转交/接活时才增加调用。"""
    del 会里的人, 原文  # 保留入口契约；新责任席不再维护群聊排队。
    from 活_本人 import 聊天唤醒, 聊天预算已满, _岗位的人 as _人
    from 平台_工具集 import 可参与岗位

    逻辑岗 = str(目标岗位) if 被点名 else 当前责任岗位(房间键)
    首岗 = 逻辑岗
    首轮理由 = (
        f"{主人称呼()}明确点名你"
        if 被点名
        else ("你在继续承接这场对话" if 逻辑岗 != "项目经理" else "你坐在大厅项目经理责任席")
    )
    本轮已说: list[tuple[str, str]] = []
    已接过: set[str] = set()
    最后回复 = ""
    最后成功逻辑岗: str | None = None
    下轮理由 = 首轮理由

    async def _进入正式工作(提议实际岗: str) -> tuple[str, bool]:
        """责任人确认是正式工作后，统一进入既有经理统筹、复核和验收链。"""
        if 逻辑岗 == "项目经理":
            进度(f"{_人(提议实际岗)}听出这是正式工作，正带全套工具上岗。")
            统筹话 = text
        else:
            进度(f"{_人(提议实际岗)}听出这是正式工作，按班规交项目经理统筹。")
            点名约束 = (
                f"{主人称呼()}明确点名『{逻辑岗}』；你必须把执行责任交给该岗位。"
                if 被点名 and 逻辑岗 == 首岗 else ""
            )
            统筹话 = (
                f"{text}\n\n（{_人(提议实际岗)}已经先听见并判断这是正式工作，现按班规交你统筹。"
                f"{点名约束}自己办、派人、开会还是请示由你判断，但不能绕过复核和验收链。）"
            )
        办岗, 工作回 = await _唤醒统筹(
            "项目经理", 统筹话, progress=进度, 会话id=sid,
            失败原因=f"{_人(提议实际岗)}转正式工作时项目经理未能到岗",
        )
        工作回 = str(工作回 or "").strip()
        已落 = False
        if _是发言(工作回):
            _落一句(办岗, 工作回, sid, 本场发言, 发群聊事件=False)
            已落 = True
        _记责任席("项目经理", 房间键, "已进入正式工作，经理席负责收敛", 进度)
        if 已落:
            try:
                import 待验收记录
                待验收记录.半强制留痕(办岗, 原话, 工作回)
            except Exception:  # noqa: BLE001
                pass
        return (工作回 if _是发言(工作回) else ""), 已落

    while True:
        动作: dict = {}
        已接过.add(逻辑岗)
        try:
            if 逻辑岗 == "项目经理":
                实际岗, 回 = await _唤醒聊天统筹(
                    "项目经理",
                    本轮已说,
                    progress=进度,
                    会话id=sid,
                    上下文窗口=默认上下文窗口,
                    唤醒理由=下轮理由,
                    聊天动作=动作,
                )
            else:
                实际岗 = 逻辑岗
                回 = await 聊天唤醒(
                    逻辑岗,
                    本轮已说,
                    会话id=sid,
                    progress=进度,
                    上下文窗口=默认上下文窗口,
                    唤醒理由=下轮理由,
                    聊天动作=动作,
                )
        except Exception as e:  # noqa: BLE001
            if isinstance(e, 聊天预算已满):
                进度("大厅已到本轮防失控上限，停止继续叫人；这不是任何员工掉线。")
                raise
            # 明确点名的人没到，不让经理冒充他回答。未点名的承接人失效则由经理席接住。
            if 被点名 and 逻辑岗 == 首岗 and 最后成功逻辑岗 is None:
                进度(f"{_人(逻辑岗)}未能到岗（{type(e).__name__}）；这是点名对话，没有改叫项目经理代答。")
                raise RuntimeError(f"{_人(逻辑岗)}未能到岗；这是点名对话，没有让项目经理代答") from e
            if 最后成功逻辑岗 is not None:
                进度(f"{_人(逻辑岗)}未能接住转交；责任席仍留在{_人(最后成功逻辑岗)}。")
                _记责任席(最后成功逻辑岗, 房间键, "转交对象未能到岗，原承接人保留", 进度)
                return 最后回复, bool(最后回复)
            if 逻辑岗 != "项目经理":
                进度(f"{_人(逻辑岗)}未能续接，大厅回到项目经理责任席。")
                逻辑岗 = "项目经理"
                下轮理由 = "原对话承接人未能到岗，你坐回经理责任席接住这句话"
                continue
            raise

        回 = str(回 or "").strip()
        if 回 == "[转办事]":
            return await _进入正式工作(实际岗)

        有发言 = _是发言(回)
        有转交 = bool(动作.get("转交岗位"))
        有邀请 = bool(动作.get("邀请岗位"))
        if 有发言:
            人, 发言 = _落一句(实际岗, 回, sid, 本场发言, 发群聊事件=True)
            最后回复 = 发言
            最后成功逻辑岗 = 逻辑岗
        elif 有转交 or 有邀请:
            # 工具调用本身就是明确责任动作；即使模型没补一句场面话，也继续转交。
            最后成功逻辑岗 = 逻辑岗
        else:
            if 被点名 and 逻辑岗 == 首岗:
                raise RuntimeError(f"{_人(实际岗)}已到岗但没有回应；这是点名对话，没有让项目经理代答")
            if 逻辑岗 != "项目经理":
                进度(f"{_人(实际岗)}没有接话，大厅回项目经理责任席接住。")
                逻辑岗 = "项目经理"
                下轮理由 = "原对话承接人没有回应，你坐回经理责任席接住"
                continue
            return "", False

        转岗 = str(动作.get("转交岗位") or "").strip()
        邀请岗位 = list(动作.get("邀请岗位") or [])
        if 转岗 and 邀请岗位:
            进度(f"{_人(实际岗)}同一轮既提出公开邀请又提出转交；责任变更优先，本轮不执行公开邀请。")
            邀请岗位 = []
        if 转岗:
            try:
                有效转岗 = 转岗 in 可参与岗位()
            except Exception:  # noqa: BLE001
                有效转岗 = False
            if not 有效转岗:
                进度(f"{_人(实际岗)}提出的转交岗位无法确认，责任席不变。")
            elif 转岗 in 已接过:
                进度(f"对话转交不能绕回{_人(转岗)}，责任席留在{_人(逻辑岗)}。")
            else:
                原因 = str(动作.get("转交原因") or "").strip()
                进度(f"{_人(实际岗)}把这场对话明确交给{_人(转岗)}（{转岗}）。")
                逻辑岗 = 转岗
                下轮理由 = f"{_人(实际岗)}明确把后续对话交给你" + (f"：{原因}" if 原因 else "")
                continue

        if 邀请岗位:
            原因 = str(动作.get("邀请原因") or "").strip()
            try:
                现役岗位 = 可参与岗位()
            except Exception:  # noqa: BLE001
                现役岗位 = set()
            邀请岗位 = [
                岗 for 岗 in dict.fromkeys(邀请岗位)
                if 岗 in 现役岗位 and 岗 not in {逻辑岗, 实际岗}
            ]
            if 邀请岗位:
                进度(f"{_人(实际岗)}请{'、'.join(_人(岗) for 岗 in 邀请岗位)}在大厅亲自说。")
                事件总线.发布事件(sid, {
                    "类型": "公开回应开始",
                    "邀请人": _人(实际岗),
                    "人数": len(邀请岗位),
                    "成员": [_人(岗) for 岗 in 邀请岗位],
                })
            提醒们: list[tuple[str, str]] = []

            async def _请一位(邀岗: str) -> tuple[str, str, dict, Exception | None]:
                邀动作: dict = {}
                try:
                    邀回 = await 聊天唤醒(
                        邀岗,
                        会话id=sid,
                        progress=进度,
                        上下文窗口=默认上下文窗口,
                        唤醒理由=(
                            f"{_人(实际岗)}请你针对{主人称呼()}刚才的话公开说自己的那份"
                            + (f"：{原因}" if 原因 else "")
                        ),
                        聊天动作=邀动作,
                        受邀发言=True,
                    )
                except Exception as e:  # noqa: BLE001
                    return 邀岗, "", 邀动作, e
                return 邀岗, str(邀回 or "").strip(), 邀动作, None

            # 公开回应彼此独立：同时叫到，谁先答完谁先出现。大厅讨论需要互相接话时应进会议室，
            # 这里不把前一人的答案塞给后一人，也不让四个人排队增加等待。
            邀请任务 = [asyncio.create_task(_请一位(邀岗)) for 邀岗 in 邀请岗位]
            for 已完成 in asyncio.as_completed(邀请任务):
                邀岗, 邀回, 邀动作, 邀错 = await 已完成
                if 邀错 is not None:
                    if isinstance(邀错, 聊天预算已满):
                        进度("大厅已到本轮防失控上限；已说的话保留，责任席不变。")
                    else:
                        进度(f"{_人(邀岗)}这轮未能到岗（{type(邀错).__name__}），其他人继续说，责任席不变。")
                    continue
                if _是发言(邀回):
                    _人名, 邀发言 = _落一句(邀岗, 邀回, sid, 本场发言, 发群聊事件=True)
                    最后回复 = 邀发言
                else:
                    进度(f"{_人(邀岗)}这轮没有开口，责任席不变。")
                for 提醒 in list(邀动作.get("提醒承接人") or []):
                    提醒们.append((邀岗, str(提醒)))

            if 提醒们:
                提醒摘要 = "；".join(f"{_人(岗)}：{原因}" for 岗, 原因 in 提醒们)
                进度(f"受邀同事提醒这件事可能需要正式处理，交回{_人(实际岗)}复核。")
                try:
                    if 逻辑岗 == "项目经理":
                        复核实际岗, 复核回 = await _唤醒聊天统筹(
                            "项目经理", [], progress=进度, 会话id=sid,
                            上下文窗口=默认上下文窗口,
                            唤醒理由=f"受邀同事的提醒：{提醒摘要}",
                            聊天动作={}, 复核提醒=True,
                        )
                    else:
                        复核实际岗 = 逻辑岗
                        复核回 = await 聊天唤醒(
                            逻辑岗, 会话id=sid, progress=进度,
                            上下文窗口=默认上下文窗口,
                            唤醒理由=f"受邀同事的提醒：{提醒摘要}",
                            聊天动作={}, 复核提醒=True,
                        )
                except Exception as e:  # noqa: BLE001
                    if isinstance(e, 聊天预算已满):
                        进度("大厅已到本轮防失控上限；提醒和公开发言已保留，责任席不变。")
                    else:
                        进度(f"{_人(逻辑岗)}未能完成提醒复核（{type(e).__name__}）；提醒和公开发言已保留，责任席不变。")
                else:
                    复核回 = str(复核回 or "").strip()
                    if 复核回 == "[转办事]":
                        return await _进入正式工作(复核实际岗)
                    if _是发言(复核回):
                        _人名, 复核发言 = _落一句(复核实际岗, 复核回, sid, 本场发言, 发群聊事件=True)
                        最后回复 = 复核发言

        _记责任席(逻辑岗, 房间键, "点名或明确承接成功", 进度)
        return 最后回复, True
